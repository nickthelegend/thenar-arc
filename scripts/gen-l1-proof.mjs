/**
 * Turn the committed L1 transcript into a module the app can render.
 *
 * The page used to read docs/l1-proof.txt with readFileSync at request time.
 * That works locally and quietly does not on the deployed host: Next traces the
 * files a route needs by following its imports, and a path assembled at runtime
 * is invisible to that trace — the file is simply not in the bundle, and the
 * page renders its "no artefact" branch on production while looking correct in
 * dev. Same failure shape as the unanchored .vercelignore entry: builds fine,
 * ships empty.
 *
 * So the transcript stays the source of truth and this emits it as data:
 *
 *   node scripts/l1.mjs > docs/l1-proof.txt   # produce it, against a real L1
 *   node scripts/gen-l1-proof.mjs             # publish it to the app
 */
import { readFileSync, writeFileSync } from "node:fs";

const raw = readFileSync("docs/l1-proof.txt", "utf8");

const claims = [];
let current = null;
let verdict = null;

for (const line of raw.split("\n")) {
  const head = line.match(/^(\d+)\s+—\s+(.+)$/);
  if (head) {
    current = { n: head[1], title: head[2].trim(), lines: [] };
    claims.push(current);
    continue;
  }
  if (/^\d+:\s*shown/.test(line.trim())) {
    verdict = line.trim().replace(/\s+/g, " ");
    continue;
  }
  if (current && line.trim()) current.lines.push(line.replace(/^ {2}/, "").trimEnd());
}

if (claims.length === 0) {
  console.error("docs/l1-proof.txt parsed to zero claims — refusing to emit an empty module.");
  process.exit(1);
}

const out =
  `// Generated by scripts/gen-l1-proof.mjs from docs/l1-proof.txt — do not edit by hand.\n` +
  `// The transcript is the artefact; this is only how it reaches the browser.\n\n` +
  `export type L1Claim = { n: string; title: string; lines: string[] };\n\n` +
  `export const L1_CLAIMS: L1Claim[] = ${JSON.stringify(claims, null, 2)};\n\n` +
  `export const L1_VERDICT = ${JSON.stringify(verdict)};\n`;

writeFileSync("lib/l1-proof.ts", out);
console.log(`lib/l1-proof.ts — ${claims.length} claims${verdict ? `, verdict "${verdict}"` : ""}`);
